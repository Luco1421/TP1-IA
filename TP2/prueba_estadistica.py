tratamientos = {
    "TF-IDF": TFIDF,
    "BERT": BERT,
    "SmolLM3 sin shots": SMOLLM3_SIN_SHOTS,
    "SmolLM3 2 shots": SMOLLM3_2_SHOTS,
    "Phi-4 sin shots": PHI4_SIN_SHOTS,
    "Phi-4 2 shots": PHI4_2_SHOTS,
}

def main():
    nombres = list(tratamientos)
    valores = [tratamientos[n] for n in nombres]
    matriz = np.column_stack(valores)

    # Friedman
    stat, p_friedman = friedmanchisquare(*valores)
    # Calcular rangos medios para reporte
    rangos = np.argsort(np.argsort(-matriz, axis=1), axis=1) + 1
    rangos_medios = rangos.mean(axis=0)

    print("Resumen por tratamiento")
    for nombre, v, r in zip(nombres, valores, rangos_medios):
        print(f"{nombre:20s} media={v.mean():.6f} std={v.std(ddof=1):.6f} rango_medio={r:.3f}")

    print("\nPrueba de Friedman")
    print(f"chi2 = {stat:.6f}  p = {p_friedman:.6g}")

    # Post-hoc Wilcoxon
    comparaciones = []
    p_vals = []
    for i, j in combinations(range(len(nombres)), 2):
        w, p = wilcoxon(valores[i], valores[j], zero_method="wilcox")
        comparaciones.append((nombres[i], nombres[j], w, p))
        p_vals.append(p)

    _, p_holm, _, _ = multipletests(p_vals, method='holm')
    print("\nPost-hoc Wilcoxon pareado con corrección Holm")
    for (a, b, w, p), ph in zip(comparaciones, p_holm):
        sig = "si" if ph < 0.05 else "no"
        print(f"{a:20s} vs {b:20s} W={w:7.3f} p={p:.6g} p_holm={ph:.6g} sig={sig}")

if __name__ == "__main__":
    main()